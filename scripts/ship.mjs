import { execFileSync } from 'node:child_process';
const git = (...args) => execFileSync('git',args,{stdio:'inherit'});
const staged = execFileSync('git',['diff','--cached','--name-only'],{encoding:'utf8'}).trim();
if (!staged) throw new Error('Stage the intended files with git add before shipping. Private or unrelated files are never staged automatically.');
if (!process.env.npm_execpath) throw new Error('Run this command through npm run ship.');
execFileSync(process.execPath,[process.env.npm_execpath,'run','verify:release'],{stdio:'inherit'});
git('diff','--cached','--check');
git('commit','-m',process.argv.slice(2).join(' ').trim() || 'Update survey app');
git('push');
console.log('Pushed. Verify the Vercel deployment before reporting it live. Native configuration changes require an updated APK.');
